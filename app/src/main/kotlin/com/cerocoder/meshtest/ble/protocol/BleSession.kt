package com.cerocoder.meshtest.ble.protocol

/**
 * Открытая сессия с нодой: готовый к работе клиент и способ её закрыть.
 *
 * Существует ради проверяемости. Транспорт получает функцию открытия сессии
 * извне, поэтому его цикл переподключения, порядок операций и освобождение
 * ресурсов тестируются на JVM — без Android, без Nordic и без ноды.
 */
interface BleSession {

    /** Клиент, через который идёт протокол. Валиден до вызова [close]. */
    val client: MeshGattClient

    /** Закрыть сессию и освободить ресурсы. Повторный вызов безопасен. */
    /**
     * Приостановиться до разрыва связи, о котором сообщил стек Bluetooth.
     *
     * Без этого сигнала сессия, умершая в тишине, не заканчивается никогда:
     * уведомления FROMNUM просто перестают приходить (поток Nordic закрывается
     * пустым `awaitClose` и не отдаёт ни ошибки, ни завершения), читать никто не
     * пробует, значит ничто и не бросает — а цикл переподключения ждёт именно
     * завершения сессии. Разрыв обязан приходить событием, а не выясняться по
     * отказу очередной операции.
     */
    suspend fun awaitDisconnect(): String

    suspend fun close()
}
