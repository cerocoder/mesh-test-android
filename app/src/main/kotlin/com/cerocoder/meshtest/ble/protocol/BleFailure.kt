package com.cerocoder.meshtest.ble.protocol

/**
 * Отказ на уровне BLE, уже описанный человеческим языком.
 *
 * Существует ради того, чтобы причина дошла до экрана, не таща за собой типы
 * библиотеки. Слой Nordic превращает свои исключения в это, а транспорт —
 * чистый JVM-код — просто берёт готовый [description] и отдаёт его наверх.
 * Сообщение исходного исключения на экран не попадает: пользователю оно ничего
 * не объясняет, а подробности реализации выносит наружу.
 */
class BleFailure(
    val description: String,
    cause: Throwable? = null,
) : Exception(description, cause)
